lines=['package com.indianservers.aiexplorer','', '// Generated by scripts/generate_math_keyboard_graph_cases.py; expected numbers use Python math, independently of the app.', 'data class KeyboardGraphCase(val id: String, val dimension: Int, val kind: String, val source: String, val expected: Double, val x: Double, val y: Double, val z: Double)', '', 'object KeyboardGraphCases {','    val all = listOf(']
manual=['MATH KEYBOARD GRAPH MANUAL CHECKLIST','300 cases: 150 for 2D and 150 for 3D.','Status: automated keyboard-action replay; physical phone execution NOT performed.','For each case: open the indicated graph workspace; clear the input; use only MathKeyboard; press Done/Add.','Digits and operators: tap the matching keys. Powers ^2/^3: long-press 2/3.','Functions: choose the function key, fill its argument, then use the right-arrow to leave the template.','Use abc for letters and semicolon; sym for <=. For sqrt, hold x² on Math+ and select √x. Invalid cases must show an error and keep the app responsive.','At each valid case: inspect the plot, pan/zoom, edit one digit, undo, and re-add. Confirm native keyboard stays hidden.','For explicit cases verify the trace/surface coordinate below. Implicit cases list a point on the relation.','Record physical-device PASS/FAIL, device model, Android version, and any crash separately.','']
def keyboard_steps(source):
    steps=[]; stack=[]; i=0
    while i<len(source):
        ch=source[i]
        if ch=='^' and i+1<len(source) and source[i+1].isdigit():
            steps.append('HOLD '+source[i+1]); i+=2; continue
        match=re.match(r'(sin|cos|sqrt|abs|exp|ln)\(',source[i:])
        if match:
            steps.append('TAP '+match[1]+' template');stack.append(True);i+=len(match[0]);continue
        if ch==')' and stack and stack[-1]:
            steps.append('TAP right arrow');stack.pop();i+=1;continue
        token='<=' if source[i:i+2]=='<=' else ch
        steps.append('TAP '+token)
        if ch=='(':stack.append(False)
        if ch==')' and stack:stack.pop()
        i+=len(token)
    return ' -> '.join(steps)+' -> TAP Done/Add'

