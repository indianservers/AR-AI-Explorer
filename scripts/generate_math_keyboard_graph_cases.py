for c in cases:
    counts[c['dim']]+=1;c['id']=f"{c['dim']}D-{counts[c['dim']]:03}"
    args=[json.dumps(c['id']),str(c['dim']),json.dumps(c['kind']),json.dumps(c['source']),repr(float(c['expected'])),repr(float(c['x'])),repr(float(c['y'])),repr(float(c['z']))]
    lines.append('        KeyboardGraphCase('+', '.join(args)+'),')
    expectation='Show validation error; no crash' if c['kind']=='invalid' else f"{c['kind']}: x={c['x']}, y={c['y']}, z={c['z']}; expected value={c['expected']}"
    if c['kind'] in ('polar','parametric') and c['dim']==2:
        expectation=f"At parameter 0: point ({c['expected']}, 0); visible curve"
    elif c['kind']=='parametric' and c['dim']==3:
        expectation=f"At u={c['x']}, v={c['y']}: point ({c['x']}, {c['y']}, {c['expected']}); visible surface"
    elif c['kind']=='inequality':
        expectation='Shade the region below and including the parabola; show its boundary; no crash'
    manual.extend([f"{c['id']} | {c['source']}",f"Keys: {keyboard_steps(c['source'])}",f"Expected: {expectation}",'Physical device result: NOT RUN',''])
lines.extend(['    )','}'])
